namespace local_wisa;

/**
 * Exposes source-column mapping metadata without exposing source-row values.
 *
 * @package    local_wisa
 * @copyright  2026 Sebsoft.nl <helpdesk@sebsoft.nl>
 * @license    http://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */
interface mapping_provider_interface {
    /**
     * Return the effective mapping for preview consumers.
     *
     * Each result is keyed by record type and generic target. A target contains
     * source, defaultsource, and overridden values only; no source-row data is returned.
     *
     * @return array Effective mappings keyed by record type and generic target.
     */
    public function get_effective_map(): array;
}
